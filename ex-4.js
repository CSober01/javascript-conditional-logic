// Switch Statement
let lightBulbStatus = "On";

//Start coding here
function checkLight(lightBulbStatus) {
  switch (lightBulbStatus) {
    case "On":
      console.log("Light bulb is On.");
      break;
    case "Off":
      console.log("Light bulb is Off.");
  }
}

checkLight(lightBulbStatus);
